class BlueprintNumberedCanvas(canvas.Canvas):
    """Two-pass canvas for dynamic total page count ('Page X of Y') and document header/footer."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self._saved_page_states: list[dict[str, Any]] = []
        self.domain_title = "Product Architecture Dossier"

    def showPage(self) -> None:
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self._draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def _draw_page_decorations(self, total_pages: int) -> None:
        self.saveState()
        page_width, page_height = letter
        margin = 42

        # 1. Top Decorative Brand Strip (Deep Indigo)
        self.setFillColor(colors.HexColor("#312e81"))
        self.rect(0, page_height - 6, page_width, 6, fill=1, stroke=0)

        # 2. Running Header
        self.setFillColor(colors.HexColor("#475569"))
        self.setFont("Helvetica-Bold", 8)
        self.drawString(margin, page_height - 22, "VISUAL REVERSE-ENGINEERING ARCHITECTURE DOSSIER")
        self.setFont("Helvetica", 8)
        self.drawRightString(
            page_width - margin,
            page_height - 22,
            f"{self.domain_title} | Technical Confidential",
        )

        # 3. Running Footer
        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.6)
        self.line(margin, 34, page_width - margin, 34)

        self.setFillColor(colors.HexColor("#64748b"))
        self.setFont("Helvetica", 7.5)
        self.drawString(margin, 20, "Generated by Ethical AI Architecture Engine - Boardroom Edition")
        self.setFont("Helvetica-Bold", 7.5)
        self.drawRightString(
            page_width - margin,
            20,
            f"Page {self._pageNumber} of {total_pages}",
        )
        self.restoreState()


