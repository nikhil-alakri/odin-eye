    def _render_design_tokens(self) -> list[Any]:
        """Renders 3-column Designer Color Swatch Grid and core design system tokens."""
        story: list[Any] = []
        story.append(Paragraph("6. Extracted UI Design System & Real Color Palette", self.s_h1))
        story.append(HRFlowable(width="100%", thickness=1, color=self.c_indigo, spaceAfter=8))
        story.append(
            Paragraph(
                "Reverse-engineered design tokens, semantic color palette swatches, typography scale, and layout elevation rules:",
                self.s_body,
            )
        )
        story.append(Spacer(1, 6))

        # Extract tokens or provide verified palette
        tokens = self.bp.design_tokens or {}
        colors_dict = tokens.get("colors", {})

        # Define 9 comprehensive design palette swatches
        palette_specs = [
            ("Primary Brand", colors_dict.get("primary", "#4f46e5"), "Primary CTAs, Active States, Focus Rings"),
            ("Secondary Accent", colors_dict.get("accent_teal", "#0d9488"), "Sparklines, Metric Badges, Highlights"),
            ("Canvas Surface", colors_dict.get("surface", "#ffffff"), "Card Backgrounds, Modals, Content Panels"),
            ("Neutral Canvas", colors_dict.get("background", "#f8fafc"), "Shell Background, Rail Containers"),
            ("Dark Typography", colors_dict.get("text_primary", "#0f172a"), "Headers, High-Contrast Labels, Body"),
            ("Muted Typography", colors_dict.get("text_muted", "#64748b"), "Subtitles, Timestamps, Placeholders"),
            ("Border & Rules", colors_dict.get("border", "#e2e8f0"), "Card Outlines, Table Dividers, Grid"),
            ("Success Metric", colors_dict.get("accent_success", "#059669"), "Positive Deltas, Verified Badges"),
            ("Danger / Alert", colors_dict.get("accent_danger", "#e11d48"), "Destructive Actions, Error Validation"),
        ]

        # Build 3-column Designer Swatch Grid
        # Table colWidths: [170, 9, 170, 9, 170]
        swatch_table_rows = []
        swatch_styles = []

        # Process in chunks of 3
        current_row_idx = 0
        for i in range(0, len(palette_specs), 3):
            chunk = palette_specs[i : i + 3]
            while len(chunk) < 3:
                chunk.append(("", "", ""))

            # Row 1: Swatch Color Block
            swatch_table_rows.append(["", "", "", "", ""])
            for col_idx, (title, hex_val, role) in enumerate(chunk):
                table_col = col_idx * 2
                if hex_val:
                    try:
                        c_swatch = colors.HexColor(hex_val)
                    except Exception:
                        c_swatch = self.c_muted
                    swatch_styles.append(("BACKGROUND", (table_col, current_row_idx), (table_col, current_row_idx), c_swatch))
                    # Add border for light colors
                    if hex_val.lower() in ("#ffffff", "#f8fafc", "#ffffff"):
                        swatch_styles.append(("BOX", (table_col, current_row_idx), (table_col, current_row_idx), 0.6, colors.HexColor("#cbd5e1")))
                    else:
                        swatch_styles.append(("BOX", (table_col, current_row_idx), (table_col, current_row_idx), 0.5, colors.HexColor("#94a3b8")))
            current_row_idx += 1

            # Row 2: Title
            r_title = []
            for col_idx, (title, hex_val, role) in enumerate(chunk):
                r_title.extend([Paragraph(f"<b>{title}</b>", self.s_swatch_title) if title else "", ""])
            swatch_table_rows.append(r_title[:5])
            current_row_idx += 1

            # Row 3: Hex & RGB
            r_hex = []
            for col_idx, (title, hex_val, role) in enumerate(chunk):
                if hex_val:
                    try:
                        c_obj = colors.HexColor(hex_val)
                        rgb_str = f"rgb({int(c_obj.red*255)}, {int(c_obj.green*255)}, {int(c_obj.blue*255)})"
                    except Exception:
                        rgb_str = "rgb(100, 116, 139)"
                    hex_p = Paragraph(f"<code>{hex_val.upper()}</code> &bull; <font color='#64748b'>{rgb_str}</font>", self.s_swatch_hex)
                else:
                    hex_p = ""
                r_hex.extend([hex_p, ""])
            swatch_table_rows.append(r_hex[:5])
            current_row_idx += 1

            # Row 4: Semantic Role
            r_role = []
            for col_idx, (title, hex_val, role) in enumerate(chunk):
                r_role.extend([Paragraph(role, self.s_swatch_role) if role else "", ""])
            swatch_table_rows.append(r_role[:5])
            current_row_idx += 1

            # Row 5: Gap Spacer Row
            swatch_table_rows.append(["", "", "", "", ""])
            current_row_idx += 1

        t_swatches = Table(swatch_table_rows, colWidths=[170, 9, 170, 9, 170])
        # Apply padding and alignments
        base_swatch_styles = [
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("TOPPADDING", (0, 0), (-1, -1), 1),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 1),
            ("LEFTPADDING", (0, 0), (-1, -1), 2),
            ("RIGHTPADDING", (0, 0), (-1, -1), 2),
        ]
        # Set height for swatch blocks
        for r_idx in range(0, current_row_idx, 5):
            base_swatch_styles.append(("BOTTOMPADDING", (0, r_idx), (-1, r_idx), 18))
        t_swatches.setStyle(TableStyle(base_swatch_styles + swatch_styles))

        story.append(KeepTogether([Paragraph("Color Palette System (Hex, RGB & Semantic Roles)", self.s_h2), t_swatches]))
        story.append(Spacer(1, 10))

        # Typography & Layout Tokens Table
        tokens_th = [
            Paragraph("Category", self.s_table_th),
            Paragraph("Design Token Key", self.s_table_th),
            Paragraph("Value / Spec", self.s_table_th),
            Paragraph("System Implementation", self.s_table_th),
        ]
        system_tokens = [
            tokens_th,
            [
                Paragraph("Typography", self.s_table_td),
                Paragraph("--font-family-sans", self.s_table_td_mono),
                Paragraph("Inter, system-ui, sans-serif", self.s_table_td),
                Paragraph("Primary interface font stack across views", self.s_table_td),
            ],
            [
                Paragraph("Typography", self.s_table_td),
                Paragraph("--font-family-mono", self.s_table_td_mono),
                Paragraph("JetBrains Mono, Menlo, monospace", self.s_table_td),
                Paragraph("Used in API paths, JSON payloads & tokens", self.s_table_td),
            ],
            [
                Paragraph("Border Radius", self.s_table_td),
                Paragraph("--radius-card / --radius-pill", self.s_table_td_mono),
                Paragraph("6px (cards) / 9999px (badges)", self.s_table_td),
                Paragraph("Card boundaries & status pill indicators", self.s_table_td),
            ],
            [
                Paragraph("Shadow / Depth", self.s_table_td),
                Paragraph("--shadow-elevation-1", self.s_table_td_mono),
                Paragraph("0 1px 3px rgba(15,23,42,0.08)", self.s_table_td),
                Paragraph("Card depth, dropdown menus & modal sheets", self.s_table_td),
            ],
        ]
        t_sys_tokens = Table(system_tokens, colWidths=[90, 140, 150, 148])
        t_sys_tokens.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), self.c_primary),
                    ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, self.c_surface]),
                    ("GRID", (0, 0), (-1, -1), 0.4, self.c_border),
                    ("TOPPADDING", (0, 0), (-1, -1), 3),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                    ("LEFTPADDING", (0, 0), (-1, -1), 5),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 5),
                ]
            )
        )
        story.append(KeepTogether([Paragraph("Typography & Layout Elevation Specifications", self.s_h2), t_sys_tokens]))
        return story

    def build_pdf(self, target_path_or_buf: str | Path | io.BytesIO | None = None) -> bytes:
        """Assemble all sections into a publication-ready PDF document."""
        if isinstance(target_path_or_buf, (str, Path)):
            buf = io.BytesIO()
            save_to_file = True
            out_path = Path(target_path_or_buf)
        else:
            buf = target_path_or_buf or io.BytesIO()
            save_to_file = False
            out_path = None

        doc = SimpleDocTemplate(
            buf,
            pagesize=letter,
            leftMargin=42,
            rightMargin=42,
            topMargin=36,
            bottomMargin=42,
        )

        story: list[Any] = []
        # Page 1: Executive Overview & Architectural Radar
        story.extend(self._render_executive_header())
        story.extend(self._render_executive_overview())
        story.append(PageBreak())

        # Page 2: Screen Navigation & State Transition Matrix
        story.extend(self._render_screen_navigation_matrix())
        story.append(PageBreak())

        # Page 3: Relational Data Architecture & ERD Entities
        story.extend(self._render_relational_schema())
        story.append(PageBreak())

        # Page 4: REST API Specifications (Stripe/Swagger-Style Cards)
        story.extend(self._render_api_contracts())
        story.append(PageBreak())

        # Page 5: Frontend Architecture Wireframe Blueprint & Component Hierarchy
        story.extend(self._render_frontend_components())
        story.append(PageBreak())

        # Page 6: Extracted UI Design System & Real Color Palette Swatches
        story.extend(self._render_design_tokens())

        # Build document using BlueprintNumberedCanvas for exact 'Page X of Y' pagination
        canvas_cls = BlueprintNumberedCanvas
        canvas_cls.domain_title = f"{self.bp.domain}"
        doc.build(story, canvasmaker=canvas_cls)

        pdf_bytes = buf.getvalue()
        if save_to_file and out_path:
            out_path.parent.mkdir(parents=True, exist_ok=True)
            out_path.write_bytes(pdf_bytes)
        return pdf_bytes

