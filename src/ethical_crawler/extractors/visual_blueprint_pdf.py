    @staticmethod
    def _escape(text: str) -> str:
        """Escape text for ReportLab XML paragraph tags."""
        if not text:
            return ""
        s = str(text)
        s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        return s

